    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text('3. Delivery Performance Metrics', 14, 152);

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`• Average Delivery Duration: ${metrics.avgDeliveryMins} minutes`, 18, 162);
