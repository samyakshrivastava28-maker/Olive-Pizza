    doc.rect(0, 0, 210, 40, 'F');

    doc.setTextColor(249, 115, 22);
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('OLIVE PIZZA — EXECUTIVE MONTHLY REPORT', 14, 22);

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(12);
    doc.text(`Month: ${monthName} ${year} | Generated: ${new Date().toLocaleDateString()}`, 14, 32);

    // Summary Box
    doc.setTextColor(15, 23, 42);
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text('1. Business Performance Summary', 14, 52);

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`• Total Gross Revenue: Rs. ${metrics.totalRevenue.toLocaleString('en-IN')}`, 18, 62);
    doc.text(`• Total Orders Processed: ${metrics.totalOrders}`, 18, 70);
    doc.text(`• Completed Deliveries: ${metrics.completedOrders}`, 18, 78);
    doc.text(`• Average Order Value (AOV): Rs. ${metrics.avgOrderValue}`, 18, 86);
    doc.text(`• Active Coupons Redeemed: ${metrics.couponsUsed}`, 18, 94);

    // Payment Methods Breakdown
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text('2. Payment Method Breakdown', 14, 110);

    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');
    doc.text(`• UPI (GPay / PhonePe / Paytm): ${metrics.upiCount} orders`, 18, 120);
    doc.text(`• Cash on Delivery (COD): ${metrics.cashCount} orders`, 18, 128);
    doc.text(`• Cards & NetBanking: ${metrics.cardCount} orders`, 18, 136);

